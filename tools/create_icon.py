"""Generate checked-in launcher icons from res/main.png; requires requirements-icons.txt."""
import hashlib
from pathlib import Path
from PIL import Image


def byte_array(name, data):
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + "," for i in range(0, len(data), 16)]
    return f"inline constexpr unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    root = Path(__file__).resolve().parents[1]
    source = root / "res/main.png"
    png = source.read_bytes()
    with Image.open(source) as image:
        if image.width != image.height or image.width < 16:
            raise ValueError("The launcher icon must be square and at least 16 pixels wide")
        rgba = image.convert("RGBA")
    # Retain the original resolution; do not invent detail by upscaling.
    sizes = [(s, s) for s in (16, 20, 24, 32, 40, 48, 64, 128, 256) if s <= rgba.width]
    rgba.save(root / "assets/launcher.ico", format="ICO", sizes=sizes, bitmap_format="bmp")
    header = (
        "#pragma once\n"
        "// Generated by tools/create_icon.py from res/main.png. Do not edit.\n"
        f"// Source SHA-256: {hashlib.sha256(png).hexdigest()}\n"
        "// clang-format off\n"
        "namespace launcher::art::icon {\n"
        f"inline constexpr int width = {rgba.width}, height = {rgba.height};\n"
        + byte_array("rgba", rgba.tobytes())
        + byte_array("png", png)
        + "} // namespace launcher::art::icon\n"
    )
    (root / "assets/launcher_icon.hpp").write_text(header, encoding="utf-8", newline="\n")
    print(f"Generated {len(sizes)} Windows icon sizes and embedded {rgba.width}x{rgba.height} RGBA/PNG")


if __name__ == "__main__":
    main()
